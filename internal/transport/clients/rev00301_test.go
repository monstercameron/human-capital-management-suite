func rev00301Root(t testing.TB) string {
	t.Helper()
	_, file, _, ok := runtime.Caller(0)
	if !ok {
		t.Fatal("runtime.Caller failed")
	}
	// this file is internal/transport/clients/rev00301_test.go
	return filepath.Join(filepath.Dir(file), "..", "..", "..")
}

// TestTodo_REV_003_01 is the REV-003-01 primary test.
//
// RED: the superseded hand-written edge client still exists alongside the
// generated capability clients.
// GREEN: exactly one IntentClient/RegistryClient implementation exists — the
// generated one — and the drift check covers it.
func TestTodo_REV_003_01(t *testing.T) {
	root := rev00301Root(t)

	// The superseded duplicate must be gone.
	if _, err := os.Stat(filepath.Join(root, "internal", "transport", "edge", "client.go")); !os.IsNotExist(err) {
		t.Fatalf("internal/transport/edge/client.go still exists: exactly one IntentClient/RegistryClient implementation must remain (the generated one)")
	}

	// The canonical generated clients must exist with the generated header.
	for _, name := range []string{"intent_client.go", "registry_client.go", "procedures.go", "support.go"} {
		path := filepath.Join(root, "internal", "transport", "clients", name)
		body, err := os.ReadFile(path)
		if err != nil {
			t.Fatalf("reading %s: %v", path, err)
		}
		if !strings.Contains(string(body), "Code generated by tools/gen/clients") {
			t.Errorf("%s lacks the generated header: not the canonical generated implementation", name)
		}
	}

	// No other non-test, non-generated package may still define the duplicate
	// client types. The edge package keeps its server (handler/procedures);
	// it must not keep a client.
	edgeFiles, err := filepath.Glob(filepath.Join(root, "internal", "transport", "edge", "*.go"))
	if err != nil {
		t.Fatalf("glob edge package: %v", err)
	}
	for _, path := range edgeFiles {
		if strings.HasSuffix(path, "_test.go") {
			continue
		}
		body, err := os.ReadFile(path)
		if err != nil {
			t.Fatalf("reading %s: %v", path, err)
		}
		text := string(body)
		if strings.Contains(text, "type IntentClient") || strings.Contains(text, "type RegistryClient") ||
			strings.Contains(text, "func NewIntentClient(") || strings.Contains(text, "func NewRegistryClient(") {
			t.Errorf("%s still defines an IntentClient/RegistryClient implementation", filepath.Base(path))
		}
	}
}

