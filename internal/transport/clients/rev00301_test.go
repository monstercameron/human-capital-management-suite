// TestTodo_REV_003_01_Integration proves the generated clients are the callers
// actually used: one vector through the generated connect backend agrees with
// the same vector through the generated gRPC backend against the real edge
// and gRPC servers.
func TestTodo_REV_003_01_Integration(t *testing.T) {
	now := time.Date(2026, 9, 3, 12, 0, 0, 0, time.UTC)
	clock := func() time.Time { return now }
	verifier, err := transporttest.NewVerifier(clock)
	if err != nil {
		t.Fatalf("NewVerifier: %v", err)
	}
	token, err := transporttest.BearerToken(verifier, transporttest.DefaultClaims(now))
	if err != nil {
		t.Fatalf("BearerToken: %v", err)
	}
	intent := &transporttest.IntentHandler{}
	registry := &transporttest.RegistryHandler{}
	cfg := transporttest.Config(verifier, clock, "req-rev00301-0001", nil)

	grpcServer, err := grpcserver.NewServer(grpcserver.Options{Config: cfg, Intent: intent, Registry: registry})
	if err != nil {
		t.Fatalf("grpcserver.NewServer: %v", err)
	}
	listener := bufconn.Listen(1 << 20)
	go func() { _ = grpcServer.Serve(listener) }()
	t.Cleanup(func() {
		grpcServer.Stop()
		_ = listener.Close()
	})
	conn, err := grpc.NewClient("passthrough:///rev00301",
		grpc.WithContextDialer(func(ctx context.Context, _ string) (net.Conn, error) {
			return listener.DialContext(ctx)
		}),
		grpc.WithTransportCredentials(insecure.NewCredentials()))
	if err != nil {
		t.Fatalf("grpc.NewClient: %v", err)
	}
	t.Cleanup(func() { _ = conn.Close() })

	edgeHandler, err := edge.NewHandler(edge.Options{Config: cfg, Intent: intent, Registry: registry})
	if err != nil {
		t.Fatalf("edge.NewHandler: %v", err)
	}
	httpServer := httptest.NewServer(edgeHandler)
	t.Cleanup(httpServer.Close)

	grpcIntent := clients.NewIntentClientGRPC(conn)
	connectIntent := clients.NewIntentClientConnect(httpServer.Client(), httpServer.URL)

	ctx := context.Background()
	vector := transporttest.CanonicalCreateIntentRequest()
	opts := []clients.CallOption{
		clients.WithAuthorization(token),
		clients.WithRequestID("req-rev00301-0001"),
	}

	viaGRPC, err := grpcIntent.CreateIntent(ctx, proto.Clone(vector).(*intentsv1.CreateIntentRequest), opts...)
	if err != nil {
		t.Fatalf("gRPC CreateIntent: %v", err)
	}
	viaConnect, err := connectIntent.CreateIntent(ctx, proto.Clone(vector).(*intentsv1.CreateIntentRequest), opts...)
	if err != nil {
		t.Fatalf("connect CreateIntent: %v", err)
	}
	if !proto.Equal(viaGRPC, viaConnect) {
		t.Fatalf("generated backends disagree:\ngrpc: %v\nconnect: %v", viaGRPC, viaConnect)
	}
	if got := viaGRPC.GetIntent().GetIntentId(); got != transporttest.DeterministicIntentID(vector.GetIdempotencyKey()) {
		t.Errorf("intent id = %q, want the deterministic fixture id", got)
	}
}
