func (r *ChatStreamRuntime) RevokeTenant(hostTenantID, homeTenantID, conversationID string) {
	if r != nil && r.stream != nil {
		r.stream.RevokeTenant(hostTenantID, homeTenantID, conversationID)
	}
}

type chatServiceReader struct {
	service    chatcore.ConversationService
	membership chatMembershipResolver
	events     chatDurableEventReader
}

// chatDurableEventReader exposes the store's global outbox watermark. The
// watermark must advance over records hidden by history policy, otherwise a
// watcher repeatedly scans the same invisible prefix forever.
type chatDurableEventReader interface {
	ReadConversationEvents(context.Context, chatcore.WatchConversationRequest, uint64, int) (chatstore.EventPage, error)
}
type chatPublicSequenceMapper interface {
	ResolvePublicSequence(context.Context, string, string, uint64) (uint64, error)
}
type chatMembershipResolver interface {
	GetMembership(context.Context, string, string, string, string) (chatcore.Membership, error)
}

type chatMachineWatchResolver interface {
	MachineWatchEpoch(context.Context, string, string, chatcore.Principal) (uint64, error)
}

// Read returns one bounded page of durable conversation events. The durable
// event source is mandatory: a live WatchConversation fallback here would
// re-enter the stream this reader feeds.
func (r chatServiceReader) Read(ctx context.Context, q chatstream.ReadRequest) (chatstream.Page, error) {
	if r.service == nil || r.events == nil {
		return chatstream.Page{}, ErrChatStreamingDisabled
	}
	homeTenant := q.HomeTenantID
	if homeTenant == "" {
		homeTenant = q.TenantID
	}
	principal := chatcore.Principal{TenantID: homeTenant, SubjectID: q.SubjectID}
	limit := q.Limit
	if limit <= 0 {
		return chatstream.Page{Complete: true}, nil
	}
	page, err := r.events.ReadConversationEvents(ctx, chatcore.WatchConversationRequest{Principal: principal, TenantID: q.TenantID, ConversationID: q.ConversationID}, q.AfterSequence, limit)
	if err != nil {
		return chatstream.Page{}, err
	}
	out := make([]chatstream.Event, 0, len(page.Events))
	// The membership epoch is a property of the reader's principal and
	// conversation, not of an individual event, so it is resolved once per page.
	epoch := uint64(0)
	if len(page.Events) > 0 || len(page.EphemeralPosts) > 0 {
		epoch, err = chatMembershipEpoch(ctx, r.service, r.membership, q.TenantID, q.ConversationID, principal)
		if err != nil {
			return chatstream.Page{}, err
		}
	}
	for _, event := range page.Events {
		payload, marshalErr := json.Marshal(event.Event)
		if marshalErr != nil {
			return chatstream.Page{}, marshalErr
		}
		sequence := event.Event.Sequence
		if parsed, parseErr := strconv.ParseUint(event.ResumeCursor, 10, 64); parseErr == nil && parsed > 0 {
			sequence = parsed
		}
		out = append(out, chatstream.Event{TenantID: q.TenantID, ConversationID: q.ConversationID, Sequence: sequence, MembershipEpoch: epoch, Payload: payload})
	}
	for _, post := range page.EphemeralPosts {
		payload, marshalErr := json.Marshal(post)
		if marshalErr != nil {
			return chatstream.Page{}, marshalErr
		}
		out = append(out, chatstream.Event{
			TenantID: q.TenantID, ConversationID: q.ConversationID, Sequence: post.Sequence,
			MembershipEpoch: epoch, RecipientHomeTenantID: post.RecipientHomeTenantID, RecipientSubjectID: post.RecipientSubjectID,
			Ephemeral: true, ExpiresAt: post.ExpiresAt, Payload: payload,
		})
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Sequence < out[j].Sequence })
	return chatstream.Page{Events: out, NextSequence: page.NextOffset, Complete: page.Complete}, nil
}

type chatServiceStreamAuthorizer struct {
	service    chatcore.ConversationService
	membership chatMembershipResolver
}

func (a chatServiceStreamAuthorizer) Authorize(ctx context.Context, access chatstream.Access) error {
	if a.service == nil {
		return ErrChatStreamingDisabled
	}
	home := access.HomeTenantID
	if home == "" {
		home = access.TenantID
	}
	principal := chatcore.Principal{TenantID: home, SubjectID: access.SubjectID}
	if _, err := a.service.GetConversation(ctx, chatcore.GetConversationRequest{Principal: principal, TenantID: access.TenantID, ConversationID: access.ConversationID}); err != nil {
		return err
	}
	epoch, err := chatMembershipEpoch(ctx, a.service, a.membership, access.TenantID, access.ConversationID, principal)
	if err != nil || epoch != access.MembershipEpoch {
		return chatcore.ErrPermissionDenied
	}
	routeEpoch, err := chatRouteEpoch(ctx, a.service, access.TenantID, access.ConversationID)
	if err != nil || routeEpoch != access.RouteEpoch {
		return chatcore.ErrPermissionDenied
	}
	return nil
}

func chatMembershipEpoch(ctx context.Context, service chatcore.ConversationService, resolver chatMembershipResolver, tenantID, conversationID string, principal chatcore.Principal) (uint64, error) {
	if verified, ok := trust.FromContext(ctx); ok && verified != nil && (verified.SubjectKind() == trust.SubjectKindAgent || verified.SubjectKind() == trust.SubjectKindIntegration) {
		if verified.Tenant().String() != principal.TenantID || verified.Subject() != principal.SubjectID || principal.TenantID != tenantID {
			return 0, chatcore.ErrPermissionDenied
		}
		machines, ok := resolver.(chatMachineWatchResolver)
		if !ok {
			return 0, chatcore.ErrPermissionDenied
		}
		return machines.MachineWatchEpoch(ctx, tenantID, conversationID, principal)
	}
	if resolver != nil {
		member, err := resolver.GetMembership(ctx, tenantID, conversationID, principal.TenantID, principal.SubjectID)
		if err != nil || member.LeftAt != nil {
			return 0, chatcore.ErrPermissionDenied
		}
		return member.Revision, nil
	}
	cursor := ""
	for pageNo := 0; pageNo < 100; pageNo++ {
		page, err := service.ListMemberships(ctx, chatcore.ListMembershipsRequest{Principal: principal, TenantID: tenantID, ConversationID: conversationID, Page: chatcore.Page{Cursor: cursor, PageSize: 100}})
		if err != nil {
			return 0, err
		}
		for _, member := range page.Memberships {
			if member.HomeTenantID == principal.TenantID && member.SubjectID == principal.SubjectID && member.LeftAt == nil {
				return member.Revision, nil
			}
		}
		if page.NextCursor == "" || page.NextCursor == cursor {
			break
		}
		cursor = page.NextCursor
	}
	return 0, chatcore.ErrPermissionDenied
}

// streamingChatService is the outermost chat decorator. It owns chat admission
// (every lane, not only sends) and the event-driven half of revocation: it holds
// the stream runtime and the authority cache, so a membership removal closes the
// affected subscriptions and drops the cached facts before returning.
type streamingChatService struct {
	chatcore.ConversationService
	runtime           *ChatStreamRuntime
	membership        chatMembershipResolver
	authority         *chatAuthorityCache
	personaDM         chatcore.PersonaDMResolver
	personaInvocation *PersonaInvocationServeWiring
	// projector is Chat's reader projection, installed with the document hub's
	// access check (bindAgentSourceAccess). Without it the stream is unprojected.
	projector agentWatchProjector
	// masker applies the workspace's language filters to a live event. It runs
	// only when no projector is bound: the projector (the core service) masks
	// as part of its own projection (CHATMOD-002).
	masker chatWatchMasker
}

// chatWatchMasker is the reader's masked view of one live watch event.
type chatWatchMasker interface {
	MaskWatchEvent(context.Context, chatcore.Principal, string, string, chatcore.WatchEvent) chatcore.WatchEvent
}

// agentWatchProjector is the one method of the Chat service the live watch needs.
type agentWatchProjector interface {
	ProjectWatchEvent(context.Context, chatcore.Principal, string, string, chatcore.WatchEvent) chatcore.WatchEvent
}

// bindPersonaInvocation installs the post-commit mention handoff while leaving
// this decorator as the served ConversationService. The handoff writes through
// the already routed and audited inner service, so this layer owns send admission
// exactly once and every other optional chat port remains promoted unchanged.
func (s *streamingChatService) bindPersonaInvocation(wiring *PersonaInvocationServeWiring) error {
	if s == nil || s.ConversationService == nil || wiring == nil || wiring.Chat == nil {
		return errPersonaInvocationServeWiring
	}
	s.personaInvocation = wiring
	return nil
}

func (s *streamingChatService) sendPost(ctx context.Context, request chatcore.SendPostRequest) (chatcore.Post, error) {
	if s == nil || s.ConversationService == nil {
		return chatcore.Post{}, chatcore.ErrUnavailable
	}
	if s.personaInvocation != nil {
		return s.personaInvocation.SendPost(ctx, request)
	}
	return s.ConversationService.SendPost(ctx, request)
}

// lease reserves one chat lane for a request. A composition without a stream
// runtime has no admission to take, and the call proceeds unmetered exactly as
// it did before.
func (s *streamingChatService) lease(ctx context.Context, lane chatadmission.Lane, tenantID, conversationID string) (*chatadmission.Lease, error) {
	if s.runtime == nil || tenantID == "" || conversationID == "" {
		return nil, nil
	}
	return s.runtime.acquire(ctx, tenantID, conversationID, lane)
}

func releaseChatLease(lease *chatadmission.Lease) {
	if lease != nil {
		_ = lease.Release()
	}
}

// GetConversation, ListPosts and ListMemberships take the cheaper read lane so a
// reconnect storm or a large-channel backfill cannot starve workflow through the
// shared process.
func (s *streamingChatService) GetConversation(ctx context.Context, r chatcore.GetConversationRequest) (chatcore.Conversation, error) {
	lease, err := s.lease(ctx, chatadmission.LaneRead, r.TenantID, r.ConversationID)
	if err != nil {
		return chatcore.Conversation{}, err
	}
	defer releaseChatLease(lease)
	return s.ConversationService.GetConversation(ctx, r)
}

