// WatchConversationWithErrors is the reporting form of the watch: it hands back
// the terminal cause alongside the event stream so a transport can tell a failed
// subscription from a completed one.
func (s *streamingChatService) WatchConversationWithErrors(ctx context.Context, req chatcore.WatchConversationRequest) (<-chan chatcore.WatchEvent, <-chan error, error) {
	// after_sequence used to be refused outright here, which made the field
	// permanently unusable and turned every resubscribe that carried it into an
	// unclassified internal failure. Both starting positions are now honoured;
	// naming both at once is still a bad request, because a client that
	// disagrees with itself about where it left off has to be told so.
	if req.AfterSequence != 0 && req.ResumeCursor != "" {
		return nil, nil, chatcore.ErrInvalidArgument
	}
	if verified, ok := trust.FromContext(ctx); ok && verified != nil && (verified.SubjectKind() == trust.SubjectKindAgent || verified.SubjectKind() == trust.SubjectKindIntegration) && req.AfterSequence != 0 {
		// The public event sequence is per conversation; the stream's durable
		// offset is an outbox ID. Machines resume only with a signed cursor so
		// a caller cannot accidentally replay by treating those as equivalent.
		return nil, nil, chatcore.ErrInvalidArgument
	}
	if s.runtime == nil {
		return nil, nil, ErrChatStreamingDisabled
	}
	// The routed service verifies the invocation, current installation scope,
	// conversation policy and route before a machine receives a stream epoch.
	if _, err := s.ConversationService.GetConversation(ctx, chatcore.GetConversationRequest{Principal: req.Principal, TenantID: req.TenantID, ConversationID: req.ConversationID}); err != nil {
		return nil, nil, err
	}
	epoch, err := chatMembershipEpoch(ctx, s.ConversationService, s.membership, req.TenantID, req.ConversationID, req.Principal)
	if err != nil {
		return nil, nil, err
	}
	routeEpoch, err := chatRouteEpoch(ctx, s.ConversationService, req.TenantID, req.ConversationID)
	if err != nil {
		return nil, nil, chatStreamError(err)
	}
	if req.AfterSequence != 0 {
		mapper, ok := s.membership.(chatPublicSequenceMapper)
		if !ok || mapper == nil {
			return nil, nil, chatcore.ErrUnavailable
		}
		offset, mapErr := mapper.ResolvePublicSequence(ctx, req.TenantID, req.ConversationID, req.AfterSequence)
		if mapErr != nil {
			return nil, nil, mapErr
		}
		req.AfterSequence = offset
	}
	sub, _, err := s.runtime.Watch(ctx, chatstream.WatchRequest{TenantID: req.TenantID, HomeTenantID: req.Principal.TenantID, SubjectID: req.Principal.SubjectID, ConversationID: req.ConversationID, MembershipEpoch: epoch, RouteEpoch: routeEpoch, Cursor: req.ResumeCursor, AfterSequence: req.AfterSequence})
	if err != nil {
		return nil, nil, chatStreamError(err)
	}
	out := make(chan chatcore.WatchEvent, 32)
	// fail carries the one terminal cause. Discarding it is what made every
	// stream failure look like a healthy end of stream: a failed durable read
	// closed the subscription, this goroutine returned, the channel closed and
	// the transport answered EOF with no error at all — so a browser saw a clean
	// end 10 ms after opening and retried until it gave up.
	fail := make(chan error, 1)
	go func() {
		defer close(out)
		defer close(fail)
		defer sub.Close()
		for {
			event, nextErr := sub.Next(ctx)
			if nextErr != nil {
				if ctx.Err() == nil && !errors.Is(nextErr, context.Canceled) && !errors.Is(nextErr, chatstream.ErrClosed) {
					fail <- chatStreamError(nextErr)
				}
				return
			}
			projected, projectErr := projectChatStreamEvent(ctx, req, event, s.runtime.clock())
			if projectErr != nil {
				if errors.Is(projectErr, chatcore.ErrEphemeralExpired) {
					// Subscription.Next has already advanced its signed cursor over
					// this offset. An expired recipient envelope is a skipped record,
					// not a terminal failure for the shared conversation watch.
					continue
				}
				fail <- chatStreamError(projectErr)
				return
			}
			if s.projector != nil {
				// The stream carries the stored body. The reader's own view of an
				// agent answer's sources is decided here, the same as on a read.
				projected = s.projector.ProjectWatchEvent(ctx, req.Principal, req.TenantID, req.ConversationID, projected)
			} else if s.masker != nil {
				projected = s.masker.MaskWatchEvent(ctx, req.Principal, req.TenantID, req.ConversationID, projected)
			}
			projected.ResumeCursor = sub.Cursor()
			select {
			case out <- projected:
			case <-ctx.Done():
				return
			}
		}
	}()
	return out, fail, nil
}

func projectChatStreamEvent(ctx context.Context, request chatcore.WatchConversationRequest, event chatstream.Event, now time.Time) (chatcore.WatchEvent, error) {
	if !event.Ephemeral {
		var conversationEvent chatcore.ConversationEvent
		if err := json.Unmarshal(event.Payload, &conversationEvent); err != nil {
			return chatcore.WatchEvent{}, fmt.Errorf("chat stream payload: %w: %w", chatcore.ErrUnavailable, err)
		}
		return chatcore.WatchEvent{Event: conversationEvent}, nil
	}
	if event.TenantID != request.TenantID || event.ConversationID != request.ConversationID ||
		event.RecipientHomeTenantID != request.Principal.TenantID || event.RecipientSubjectID != request.Principal.SubjectID ||
		request.Principal.TenantID == "" || request.Principal.SubjectID == "" {
		return chatcore.WatchEvent{}, chatcore.ErrPermissionDenied
	}
	if verified, ok := trust.FromContext(ctx); ok {
		if verified.SubjectKind() != trust.SubjectKindHuman || verified.Tenant().String() != request.Principal.TenantID || verified.Subject() != request.Principal.SubjectID {
			return chatcore.WatchEvent{}, chatcore.ErrPermissionDenied
		}
	}
	if event.ExpiresAt.IsZero() {
		return chatcore.WatchEvent{}, fmt.Errorf("chat ephemeral envelope expiry: %w", chatcore.ErrUnavailable)
	}
	if !now.Before(event.ExpiresAt) {
		return chatcore.WatchEvent{}, chatcore.ErrEphemeralExpired
	}
	var post chatcore.EphemeralPost
	if err := json.Unmarshal(event.Payload, &post); err != nil {
		return chatcore.WatchEvent{}, fmt.Errorf("chat ephemeral payload: %w: %w", chatcore.ErrUnavailable, err)
	}
	if post.ExpiresAt.IsZero() {
		return chatcore.WatchEvent{}, fmt.Errorf("chat ephemeral payload expiry: %w", chatcore.ErrUnavailable)
	}
	if !now.Before(post.ExpiresAt) {
		return chatcore.WatchEvent{}, chatcore.ErrEphemeralExpired
	}
	if post.TenantID != request.TenantID || post.ConversationID != request.ConversationID ||
		post.RecipientHomeTenantID != request.Principal.TenantID || post.RecipientSubjectID != request.Principal.SubjectID ||
		post.Sequence == 0 || post.Sequence != event.Sequence || post.ID == "" || post.ThreadID == "" ||
		!post.OnlyVisibleToYou || post.Body == "" || post.CreatedAt.IsZero() || post.ThreadLink == "" ||
		!post.ExpiresAt.After(post.CreatedAt) || post.ExpiresAt.After(post.CreatedAt.Add(chatcore.EphemeralLifetime)) ||
		!post.ExpiresAt.Equal(event.ExpiresAt) || !now.Before(post.ExpiresAt) {
		return chatcore.WatchEvent{}, chatcore.ErrPermissionDenied
	}
	delivery := &chatcore.EphemeralDelivery{
		ID: post.ID, ThreadID: post.ThreadID, Body: post.Body, OnlyVisibleToYou: true,
		CreatedAt: post.CreatedAt, ExpiresAt: post.ExpiresAt, ThreadLink: post.ThreadLink,
	}
	return chatcore.WatchEvent{EphemeralDelivery: delivery}, nil
}

// WatchConversation keeps the canonical single-channel contract for callers that
// do not distinguish a failure from an end of stream.
func (s *streamingChatService) WatchConversation(ctx context.Context, req chatcore.WatchConversationRequest) (<-chan chatcore.WatchEvent, error) {
	events, _, err := s.WatchConversationWithErrors(ctx, req)
	return events, err
}

// defaultChatAdmissionConfig is the composition default. ChatComposition.Admission
// overrides any field a deployment sets; the rest keep these bounds.
func defaultChatAdmissionConfig() chatadmission.Config {
	return chatadmission.Config{TenantConcurrent: 128, ConversationConcurrent: 32, SendConcurrent: 64, WatchConcurrent: 256, ReadConcurrent: 128, DerivedConcurrent: 32, WatchTenantConcurrent: 256, WatchConversationConcurrent: 256}
}

// mergeChatAdmissionConfig applies the deployment's overrides field by field, so
// setting one bound does not silently zero the others.
func mergeChatAdmissionConfig(base, override chatadmission.Config) chatadmission.Config {
	if override.TenantConcurrent > 0 {
		base.TenantConcurrent = override.TenantConcurrent
	}
	if override.ConversationConcurrent > 0 {
		base.ConversationConcurrent = override.ConversationConcurrent
	}
	if override.SendConcurrent > 0 {
		base.SendConcurrent = override.SendConcurrent
	}
	if override.WatchConcurrent > 0 {
		base.WatchConcurrent = override.WatchConcurrent
	}
	if override.ReadConcurrent > 0 {
		base.ReadConcurrent = override.ReadConcurrent
	}
	if override.DerivedConcurrent > 0 {
		base.DerivedConcurrent = override.DerivedConcurrent
	}
	if override.WatchTenantConcurrent > 0 {
		base.WatchTenantConcurrent = override.WatchTenantConcurrent
	}
	if override.WatchConversationConcurrent > 0 {
		base.WatchConversationConcurrent = override.WatchConversationConcurrent
	}
	if override.ReadShedFraction > 0 {
		base.ReadShedFraction = override.ReadShedFraction
	}
	if override.DerivedShedFraction > 0 {
		base.DerivedShedFraction = override.DerivedShedFraction
	}
	return base
}
