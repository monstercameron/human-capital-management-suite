var ErrChatStreamingDisabled = errors.New("application: chat streaming disabled")

// ChatStreamRuntime is the composition-owned bridge for live chat. The
// cursor key is supplied by ServeConfig and never generated by this runtime.
// A missing key leaves Watch disabled, so a deployment cannot accidentally
// expose unsigned or process-local resumable cursors.
type ChatStreamRuntime struct {
	stream    *chatstream.Stream
	bridge    chatstream.Bridge
	admission *chatadmission.Admission
	clock     func() time.Time
}

type ChatStreamRuntimeConfig struct {
	CursorKey       string
	Reader          chatstream.Reader
	Authorizer      chatstream.Authorizer
	PollInterval    time.Duration
	RecheckInterval time.Duration
	PageLimit       int
	QueueSize       int
	ReplayLimit     int
	CursorTTL       time.Duration
	Budgets         chatadmission.Config
	Clock           func() time.Time
}

func NewChatStreamRuntime(c ChatStreamRuntimeConfig) (*ChatStreamRuntime, error) {
	if c.CursorKey == "" {
		return nil, ErrChatStreamingDisabled
	}
	if c.Clock == nil {
		c.Clock = time.Now
	}
	stream, err := chatstream.New(chatstream.Config{Key: []byte(c.CursorKey), Reader: c.Reader, Authorizer: c.Authorizer, QueueSize: c.QueueSize, ReplayLimit: c.ReplayLimit, CursorTTL: c.CursorTTL, Clock: c.Clock, RecheckInterval: c.RecheckInterval})
	if err != nil {
		return nil, err
	}
	admission, err := chatadmission.New(c.Budgets)
	if err != nil {
		return nil, err
	}
	return &ChatStreamRuntime{stream: stream, admission: admission, clock: c.Clock, bridge: chatstream.Bridge{Stream: stream, Reader: c.Reader, PollInterval: c.PollInterval, PageLimit: c.PageLimit}}, nil
}

func (r *ChatStreamRuntime) Watch(ctx context.Context, req chatstream.WatchRequest) (*chatstream.Subscription, *chatadmission.Lease, error) {
	if r == nil || r.stream == nil || r.admission == nil {
		return nil, nil, ErrChatStreamingDisabled
	}
	lease, err := r.admission.Acquire(ctx, chatadmission.Request{TenantID: req.TenantID, ConversationID: req.ConversationID, Lane: chatadmission.LaneWatch})
	if err != nil {
		return nil, nil, err
	}
	sub, err := r.bridge.Watch(ctx, req)
	if err != nil {
		_ = lease.Release()
		return nil, nil, err
	}
	go func() {
		<-sub.Done()
		_ = lease.Release()
	}()
	return sub, lease, nil
}

// AcquireSend reserves the chat lane before a durable SendPost transaction.
func (r *ChatStreamRuntime) AcquireSend(ctx context.Context, tenantID, conversationID string) (*chatadmission.Lease, error) {
	return r.acquire(ctx, tenantID, conversationID, chatadmission.LaneSend)
}

// AcquireRead reserves the cheaper read lane for a bounded cursor page or a
// metadata lookup. It is shed before a send but after derived work.
func (r *ChatStreamRuntime) AcquireRead(ctx context.Context, tenantID, conversationID string) (*chatadmission.Lease, error) {
	return r.acquire(ctx, tenantID, conversationID, chatadmission.LaneRead)
}

// AcquireDerived reserves the ephemeral/derived lane: reference suggestions,
// integration event pulls and similar work the spec sheds first.
func (r *ChatStreamRuntime) AcquireDerived(ctx context.Context, tenantID, conversationID string) (*chatadmission.Lease, error) {
	return r.acquire(ctx, tenantID, conversationID, chatadmission.LaneDerived)
}

func (r *ChatStreamRuntime) acquire(ctx context.Context, tenantID, conversationID string, lane chatadmission.Lane) (*chatadmission.Lease, error) {
	if r == nil || r.admission == nil {
		return nil, ErrChatStreamingDisabled
	}
	lease, err := r.admission.Acquire(ctx, chatadmission.Request{TenantID: tenantID, ConversationID: conversationID, Lane: lane})
	if err != nil {
		return nil, chatOverload(err)
	}
	return lease, nil
}

// chatOverload maps a shed or saturated lane onto the chat contract's retryable
// unavailable result, so a caller sees "retry" rather than a denial. The
// admission sentinel stays in the chain for operators and tests.
func chatOverload(err error) error {
	if errors.Is(err, chatadmission.ErrOverloaded) {
		return fmt.Errorf("%w: %w", chatcore.ErrUnavailable, err)
	}
	return err
}

// chatStreamError names a failed subscribe in the chat contract's vocabulary.
//
// Every one of these used to leave here as a bare wrapped chatstream sentinel,
// which the transport could not classify: the request log recorded one
// UNAVAILABLE transport.unclassified_failure for a bad cursor, a revoked
// membership and a saturated watch lane alike, so the whole class of watch
// failures was invisible. The original stays in the chain, so a test and an
// operator can still see which condition it was.
func chatStreamError(err error) error {
	switch {
	case err == nil:
		return nil
	case errors.Is(err, chatstream.ErrInvalidCursor), errors.Is(err, chatstream.ErrExpiredCursor):
		return fmt.Errorf("chat stream cursor: %w: %w", chatcore.ErrInvalidArgument, err)
	case errors.Is(err, chatstream.ErrUnauthorized), errors.Is(err, chatstream.ErrRevoked):
		return fmt.Errorf("chat stream authority: %w: %w", chatcore.ErrPermissionDenied, err)
	case errors.Is(err, chatadmission.ErrOverloaded), errors.Is(err, chatstream.ErrBackpressure), errors.Is(err, chatstream.ErrClosed):
		return fmt.Errorf("chat stream capacity: %w: %w", chatcore.ErrUnavailable, err)
	case errors.Is(err, chatstream.ErrInvalidConfig):
		return fmt.Errorf("chat stream configuration: %w: %w", ErrChatStreamingDisabled, err)
	}
	return fmt.Errorf("chat stream watch: %w", err)
}

// Revoke closes the live subscriptions one principal holds on a conversation.
// Membership removal calls it so revocation does not wait for the periodic
// re-authorization.
func (r *ChatStreamRuntime) Revoke(hostTenantID, homeTenantID, subjectID, conversationID string, membershipEpoch uint64) {
	if r != nil && r.stream != nil {
		r.stream.Revoke(hostTenantID, homeTenantID, subjectID, conversationID, membershipEpoch)
	}
}

// RevokeTenant closes every live subscription a consumer tenant holds on a host
