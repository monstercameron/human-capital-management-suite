func TestGenerateUsesOnlyThePinnedBuf(t *testing.T) {
	root := t.TempDir()
	target := filepath.Join(root, "gen", "go")
	if err := os.MkdirAll(filepath.Join(target, "model"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(target, "model", "model_generated.go"), []byte("package model\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(target, "old.pb.go"), []byte("// Code generated by protoc-gen-go. DO NOT EDIT.\npackage old\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	bufPath := writeTestLock(t, root)
	var calls [][]string
	run := func(_ context.Context, _ string, _ io.Writer, _ io.Writer, name string, args ...string) ([]byte, error) {
		calls = append(calls, append([]string{name}, args...))
		if reflect.DeepEqual(args, []string{"--version"}) {
			return []byte("1.72.0\n"), nil
		}
		if len(args) != 5 || args[0] != "generate" || args[1] != "--template" || args[3] != "-o" {
			t.Fatalf("unexpected generation arguments: %v", args)
		}
		generated := filepath.Join(args[4], "gen", "go")
		if err := os.MkdirAll(generated, 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(filepath.Join(generated, "new.pb.go"), []byte("// Code generated by protoc-gen-go. DO NOT EDIT.\npackage generated\n"), 0o600); err != nil {
			t.Fatal(err)
		}
		return nil, nil
	}
	var stdout, stderr bytes.Buffer
	if err := generate(context.Background(), root, &stdout, &stderr, run, func(string) (string, error) { return bufPath, nil }); err != nil {
		t.Fatalf("generate: %v", err)
	}
	if len(calls) != 2 || calls[0][0] != bufPath || !reflect.DeepEqual(calls[0][1:], []string{"--version"}) || calls[1][0] != bufPath || calls[1][1] != "generate" {
		t.Fatalf("commands = %v, want buf version check followed by generate", calls)
	}
	if _, err := os.Stat(filepath.Join(target, "model", "model_generated.go")); err != nil {
		t.Fatalf("non-Protobuf generated output was removed: %v", err)
	}
	if _, err := os.Stat(filepath.Join(target, "old.pb.go")); !os.IsNotExist(err) {
		t.Fatalf("stale Protobuf output remains: err=%v", err)
	}
	if _, err := os.Stat(filepath.Join(target, "new.pb.go")); err != nil {
		t.Fatalf("new Protobuf output was not published: %v", err)
	}
}

func TestGenerateRejectsBufVersionDrift(t *testing.T) {
	root := t.TempDir()
	if err := os.Mkdir(filepath.Join(root, "gen"), 0o755); err != nil {
		t.Fatal(err)
	}
	bufPath := writeTestLock(t, root)
	calledGenerate := false
	run := func(_ context.Context, _ string, _ io.Writer, _ io.Writer, _ string, args ...string) ([]byte, error) {
		if len(args) > 0 && args[0] == "generate" {
			calledGenerate = true
		}
		return []byte("1.71.0\n"), nil
	}
	err := generate(context.Background(), root, io.Discard, io.Discard, run, func(string) (string, error) { return bufPath, nil })
	if err == nil {
		t.Fatal("expected version drift to fail")
	}
	if calledGenerate {
		t.Fatal("generation ran after the buf version check failed")
	}
}

func TestGenerateReturnsBufCommandFailure(t *testing.T) {
	root := t.TempDir()
	if err := os.Mkdir(filepath.Join(root, "gen"), 0o755); err != nil {
		t.Fatal(err)
	}
	bufPath := writeTestLock(t, root)
	wantErr := errors.New("not found")
	run := func(_ context.Context, _ string, _ io.Writer, _ io.Writer, _ string, args ...string) ([]byte, error) {
		if len(args) > 0 && args[0] == "--version" {
			return []byte("1.72.0"), nil
		}
		return nil, wantErr
	}
	err := generate(context.Background(), root, io.Discard, io.Discard, run, func(string) (string, error) { return bufPath, nil })
	if !errors.Is(err, wantErr) {
		t.Fatalf("generate error = %v, want wrapped %v", err, wantErr)
	}
}

func writeTestLock(t *testing.T, root string) string {
	t.Helper()
	bufPath := filepath.Join(root, "buf-test-binary")
	bufBytes := []byte("test buf executable")
	if err := os.WriteFile(bufPath, bufBytes, 0o600); err != nil {
		t.Fatal(err)
	}
	digest := sha256.Sum256(bufBytes)
	lock, err := json.Marshal(toolLock{
		BufVersion: "1.72.0",
		BufBinarySHA256ByPlatform: map[string]string{
			runtime.GOOS + "/" + runtime.GOARCH: hex.EncodeToString(digest[:]),
		},
	})
	if err != nil {
		t.Fatal(err)
	}
	if err := os.MkdirAll(filepath.Join(root, "gen"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(root, "gen", "TOOLS.lock"), lock, 0o600); err != nil {
		t.Fatal(err)
	}
	return bufPath
}

