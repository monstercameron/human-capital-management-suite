// SQLDisposition is the model-owned input to SQL generation for one entity.
// It describes physical placement and the policies SQL must preserve; it is
// not a migration and never grants permission to change a live database.
type SQLDisposition struct {
	SourceRef       string
	EntityKey       string
	TableName       string
	Disposition     string
	Target          string
	TenantColumn    string
	TenantScoped    bool
	AppendOnly      bool
	RetentionClass  string
	EncryptionClass string
}

// SQLDispositionSet is the complete deterministic disposition input set.
type SQLDispositionSet struct {
	GeneratedBy        string
	RegistryDigest     string
	SpecificationOwner string
	Entities           []SQLDisposition
}

// SpecificationOwner is the accountable owner for the model-derived SQL
// disposition library. It governs generated review inputs; it is not a
// database role and grants no migration or write authority.
const SpecificationOwner = "PLATFORM_ENGINEERING_OWNER"

// MigrationPreview is a review-only CREATE TABLE skeleton. Preview files are
// deliberately emitted under tools/gen/modelgen/testdata/preview and never
// under migrations/, because a human migration owner must review and number
// an applied migration.
type MigrationPreview struct {
	FileName  string
	SourceRef string
	TableName string
	SQL       string
}

// SQLArtifacts is the complete MSRC-008 generated set.
type SQLArtifacts struct {
	Disposition SQLDispositionSet
	Previews    []MigrationPreview
}

// OutputPreviewDir is the only preview output location this generator owns.
const OutputPreviewDir = "tools/gen/modelgen/testdata/preview"

// GeneratedPreviewHeader marks every preview as generated review input.
const GeneratedPreviewHeader = "-- PREVIEW ONLY (MSRC-008): generated by tools/gen/modelgen. DO NOT EDIT."

// BuildSQLDisposition projects the immutable model registry into one SQL
// disposition row per registered entity. The physical mapping is explicit:
// aggregate stream roots use the shared ledger_event table, while the
// registry's table-backed control/evidence/read-model entities retain their
// named table. Child entities inherit their owner's physical placement.
func BuildSQLDisposition(reg *model.Registry) (SQLDispositionSet, error) {
	if reg == nil {
		return SQLDispositionSet{}, fmt.Errorf("modelgen: BuildSQLDisposition: nil registry")
	}
	properties := propertiesByEntity(reg)
	rows := make([]SQLDisposition, 0, len(reg.Entities()))
	for _, entity := range reg.Entities() {
		physical, err := physicalDisposition(reg, entity, map[string]bool{})
		if err != nil {
			return SQLDispositionSet{}, err
		}
		props := properties[entity.Ref]
		retention, encryption := policyClasses(props)
		rows = append(rows, SQLDisposition{
			SourceRef:       entity.Ref.String(),
			EntityKey:       entity.Key,
			TableName:       physical.TableName,
			Disposition:     physical.Disposition,
			Target:          physical.Target,
			TenantColumn:    tenantColumn(entity.TenantScoped),
			TenantScoped:    entity.TenantScoped,
			AppendOnly:      physical.AppendOnly || entity.Class == model.ClassEvidence,
			RetentionClass:  retention,
			EncryptionClass: encryption,
		})
	}
	return SQLDispositionSet{
		GeneratedBy:        "tools/gen/modelgen (MSRC-008)",
		RegistryDigest:     reg.Digest(),
		SpecificationOwner: SpecificationOwner,
		Entities:           rows,
	}, nil
}

// GenerateSQLDisposition is the descriptive alias used by callers that do
// not need the broader preview set.
func GenerateSQLDisposition(reg *model.Registry) (SQLDispositionSet, error) {
	return BuildSQLDisposition(reg)
}

// BuildSQLArtifacts builds the disposition set and one preview per unique
// table-backed physical target. Value objects embedded in an owner table do
// not create a second CREATE TABLE preview.
func BuildSQLArtifacts(reg *model.Registry) (SQLArtifacts, error) {
	disposition, err := BuildSQLDisposition(reg)
	if err != nil {
		return SQLArtifacts{}, err
	}
	byTable := map[string]SQLDisposition{}
	for _, row := range disposition.Entities {
		if row.TableName == "" || row.Disposition == string(storagemanifest.DispositionValueObject) {
			continue
		}
		if _, ok := byTable[row.TableName]; !ok {
			byTable[row.TableName] = row
		}
	}
	tables := make([]string, 0, len(byTable))
	for table := range byTable {
		tables = append(tables, table)
	}
	sort.Strings(tables)
	previews := make([]MigrationPreview, 0, len(tables))
	for _, table := range tables {
		row := byTable[table]
		name := table + ".sql"
		previews = append(previews, MigrationPreview{
			FileName:  name,
			SourceRef: row.SourceRef,
			TableName: table,
			SQL:       renderPreviewSQL(row),
		})
	}
	return SQLArtifacts{Disposition: disposition, Previews: previews}, nil
}

// GenerateSQLArtifacts is the descriptive alias for BuildSQLArtifacts.
func GenerateSQLArtifacts(reg *model.Registry) (SQLArtifacts, error) {
	return BuildSQLArtifacts(reg)
}

// RenderPreviewFiles returns the complete generated preview file set keyed by
// paths relative to OutputPreviewDir.
func RenderPreviewFiles(reg *model.Registry) (map[string][]byte, error) {
	artifacts, err := BuildSQLArtifacts(reg)
	if err != nil {
		return nil, err
	}
	files := make(map[string][]byte, len(artifacts.Previews))
	for _, preview := range artifacts.Previews {
		files[preview.FileName] = []byte(preview.SQL)
	}
	return files, nil
}

// WritePreviewFiles writes a rendered preview set only below
// <repoRoot>/tools/gen/modelgen/testdata/preview. The path is fixed by the
// package contract so a caller cannot accidentally turn a review input into
// an applied migration.
func WritePreviewFiles(repoRoot string, files map[string][]byte) error {
	dir := filepath.Join(repoRoot, filepath.FromSlash(OutputPreviewDir))
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return fmt.Errorf("modelgen: create preview directory: %w", err)
	}
	for _, name := range sortedFileKeys(files) {
		if name == "" || filepath.Base(name) != name || strings.Contains(filepath.ToSlash(name), "..") {
			return fmt.Errorf("modelgen: invalid preview file name %q", name)
		}
		if err := os.WriteFile(filepath.Join(dir, name), files[name], 0o644); err != nil {
			return fmt.Errorf("modelgen: write preview %s: %w", name, err)
		}
	}
	return nil
}

// SQLArtifactsDigest is a stable golden digest over the generated disposition
// rows and preview bytes.
func SQLArtifactsDigest(artifacts SQLArtifacts) string {
	h := sha256.New()
	write := func(parts ...string) {
		for _, part := range parts {
			_, _ = h.Write([]byte(part))
			_, _ = h.Write([]byte{0})
		}
	}
	write("OWNER", artifacts.Disposition.SpecificationOwner)
	write("REGISTRY", artifacts.Disposition.RegistryDigest)
	for _, row := range artifacts.Disposition.Entities {
		write("ENTITY", row.SourceRef, row.EntityKey, row.TableName, row.Disposition, row.Target, row.TenantColumn, fmt.Sprint(row.TenantScoped), fmt.Sprint(row.AppendOnly), row.RetentionClass, row.EncryptionClass)
	}
	for _, preview := range artifacts.Previews {
		write("PREVIEW", preview.FileName, preview.SourceRef, preview.TableName, preview.SQL)
	}
	return "sha256:" + hex.EncodeToString(h.Sum(nil))
}

// CompareStorageDisposition checks the overlap between this model-derived
// set and the checked-in DB-002 manifest. MISMATCH rows are intentionally
// skipped: they are migration gaps, not evidence that the model's intended
// physical target is wrong. Every existing table/event/artifact/projection
// row must still agree on entity identity and physical target.
func CompareStorageDisposition(generated SQLDispositionSet, current storagemanifest.DispositionManifest) []error {
	byRef := map[string]SQLDisposition{}
	for _, row := range generated.Entities {
		byRef[row.SourceRef] = row
	}
	var errs []error
	for _, actual := range current.Entities {
		if actual.Disposition == storagemanifest.DispositionMismatch {
			continue
		}
		row, ok := byRef[actual.EntityRef]
		if !ok {
			errs = append(errs, fmt.Errorf("storage disposition contains ungenerated entity %s", actual.EntityRef))
			continue
		}
		if row.EntityKey != actual.Key || row.Disposition != string(actual.Disposition) || row.Target != actual.Target {
			errs = append(errs, fmt.Errorf("storage disposition for %s drifts: generated=(key=%s disposition=%s target=%s), current=(key=%s disposition=%s target=%s)", actual.EntityRef, row.EntityKey, row.Disposition, row.Target, actual.Key, actual.Disposition, actual.Target))
		}
	}
	return errs
}

type physicalTarget struct {
	TableName   string
	Disposition string
	Target      string
	AppendOnly  bool
}

func physicalDisposition(reg *model.Registry, entity model.EntityDefinition, visiting map[string]bool) (physicalTarget, error) {
	if visiting[entity.Ref.String()] {
		return physicalTarget{}, fmt.Errorf("modelgen: physical disposition cycle at %s", entity.Ref)
	}
	visiting[entity.Ref.String()] = true
	defer delete(visiting, entity.Ref.String())
	if entity.Class == model.ClassChild {
		owner, err := reg.OwnerRoot(entity.Ref)
		if err != nil {
			return physicalTarget{}, fmt.Errorf("modelgen: resolve child %s: %w", entity.Ref, err)
		}
		ownerEntity, err := reg.Entity(owner)
		if err != nil {
			return physicalTarget{}, err
		}
		return physicalDisposition(reg, ownerEntity, visiting)
	}
	switch entity.Key {
	case "intent_instance":
		return physicalTarget{"intent_instance", string(storagemanifest.DispositionTable), "table intent_instance", false}, nil
	case "proposal_revision":
		return physicalTarget{"proposal_revision", string(storagemanifest.DispositionTable), "table proposal_revision", false}, nil
	case "evidence_record":
		return physicalTarget{"evidence_artifact", string(storagemanifest.DispositionArtifact), "table evidence_artifact", true}, nil
	case "observation":
		return physicalTarget{"external_observation", string(storagemanifest.DispositionTable), "table external_observation", false}, nil
	case "worker_summary":
		return physicalTarget{"projection_checkpoint", string(storagemanifest.DispositionProjection), "table projection_checkpoint", false}, nil
	case "approval_binding", "execution_binding":
		return physicalTarget{entity.Key, string(storagemanifest.DispositionArtifact), "table " + entity.Key, true}, nil
	}
	if aggregate, err := reg.Aggregate(entity.Ref); err == nil && aggregate.StreamKind != "" {
		return physicalTarget{"ledger_event", string(storagemanifest.DispositionEvent), "ledger_event via ledger_stream.stream_kind=" + aggregate.StreamKind, true}, nil
	}
	return physicalTarget{entity.Key, string(storagemanifest.DispositionTable), "table " + entity.Key, false}, nil
}

func propertiesByEntity(reg *model.Registry) map[model.EntityRef][]model.PropertyDefinition {
	properties := map[model.EntityRef][]model.PropertyDefinition{}
	for _, property := range reg.Properties() {
		properties[property.Entity] = append(properties[property.Entity], property)
	}
	return properties
}

func policyClasses(properties []model.PropertyDefinition) (string, string) {
	if len(properties) == 0 {
		return "UNSPECIFIED", "PLAINTEXT"
	}
	retention := make([]string, 0, len(properties))
	seen := map[string]bool{}
	strongest := properties[0].Classification
	for _, property := range properties {
		if !seen[property.RetentionClassRef] {
			retention = append(retention, property.RetentionClassRef)
			seen[property.RetentionClassRef] = true
		}
		if property.Classification.Rank() > strongest.Rank() {
			strongest = property.Classification
		}
	}
	sort.Strings(retention)
	return strings.Join(retention, ","), encryptionClass(strongest)
}

func encryptionClass(classification model.ClassificationLabel) string {
	if classification == model.ClassPublic || classification == model.ClassInternal {
		return "PLAINTEXT"
	}
	return "ENCRYPTED_AT_REST"
}

func tenantColumn(scoped bool) string {
	if scoped {
		return "tenant_id"
	}
	return ""
}

func renderPreviewSQL(row SQLDisposition) string {
	var b strings.Builder
	b.WriteString(GeneratedPreviewHeader + "\n")
	fmt.Fprintf(&b, "-- Source: %s; retention=%s; encryption=%s; append_only=%t\n", row.SourceRef, row.RetentionClass, row.EncryptionClass, row.AppendOnly)
	fmt.Fprintf(&b, "CREATE TABLE IF NOT EXISTS %s (\n", row.TableName)
	if row.TenantScoped {
		b.WriteString("    tenant_id tenant_ref NOT NULL,\n")
	}
	b.WriteString("    recorded_at timestamptz NOT NULL DEFAULT now()\n")
	b.WriteString(");\n")
	if row.TenantScoped {
		fmt.Fprintf(&b, "ALTER TABLE %s ENABLE ROW LEVEL SECURITY;\n", row.TableName)
		fmt.Fprintf(&b, "-- tenant_isolation policy required for %s.\n", row.TableName)
	}
	if row.AppendOnly {
		fmt.Fprintf(&b, "-- forbid_mutation trigger required for append-only target %s.\n", row.TableName)
	}
	return b.String()
}
