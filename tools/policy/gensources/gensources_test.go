// TestTodo_ARCH_GO_015_Golden pins the real definition-file denominator and
// verifies that the current legacy generatedby spelling is reported rather
// than silently accepted as the new definitions contract.
func TestTodo_ARCH_GO_015_Golden(t *testing.T) {
	report, err := Scan(repoRoot(t))
	if err != nil {
		t.Fatal(err)
	}
	var definitions int
	for _, file := range report.Files {
		if strings.HasPrefix(file.Path, "definitions/") && (strings.HasSuffix(file.Path, ".yaml") || strings.HasSuffix(file.Path, ".json")) {
			definitions++
		}
	}
	if definitions != 118 {
		t.Fatalf("definitions YAML/JSON count = %d, want pinned count 118", definitions)
	}
	if !hasRule(report.Violations, "generated-definition-missing-generated_by") {
		t.Fatal("real tree no longer reports the legacy generatedby definitions that need migration")
	}
}

